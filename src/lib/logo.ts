/**
 * @file 로고 픽셀 그림 (logo.ts)
 * 읽는 순서: 11/84번째 · 3단계(화면의 뼈대와 공통 모양)
 *   앞: src/components/pixel-art.tsx → 다음: src/lib/github-mark.ts (전체 순서와 문서 순서: docs/reading-order.md)
 *
 * 이 파일이 하는 일
 *   블로그 로고(플로피 디스크)를 글자 격자로 그려 둡니다.
 *   본 영화·읽은 책의 한 줄 평을 "기록해 저장해 두는" 블로그라는 뜻이에요. 옛 단말기 화면과도 어울려요.
 *
 *     ##########..   ← 디스크 위쪽 테두리. 오른쪽 위 귀퉁이는 비스듬히 깎여 있어요.
 *     #.#....#.##.   ← 금속 덮개(셔터): 가운데 빈 네모
 *     #.#....#.###
 *     #.######...#
 *     #..........#
 *     #.########.#   ← 이름표(라벨) 자리
 *     #.#......#.#
 *     #.#......#.#
 *     #.########.#
 *     ############   ← 아래쪽 테두리
 *
 * 쓰는 곳(그림은 LOGO_ROWS 하나예요)
 *   - components/site-header.tsx: 머리글 왼쪽에 한 칸 2px로 그려요(24 × 22px). 옆의 블로그 이름(20px 글자)과 높이·세로 가운데가 맞아요.
 *   - scripts/make-icons.mjs: 브라우저 탭 아이콘(src/app/icon.svg), 설치 앱 아이콘(public/icons/*.png, src/app/apple-icon.png),
 *     공유 미리 보기 그림(public/og.png)을 만들 때 가운데에 놓아 써요.
 *     (그림을 고친 뒤에는 `pnpm icons`를 실행해 아이콘 파일을 다시 만들어요.)
 *   세로가 가로보다 한 칸 짧은 12 × 11칸이에요. 이름표(라벨)를 세 줄로 두어, 실제 3.5인치 디스크처럼 거의 정사각형으로 보여요.
 *
 * 그림 읽는 법
 *   '#'은 색칠한 칸, '.'은 빈칸이에요.
 *   왼쪽 끝 칸(디스크 왼쪽 테두리)과 오른쪽 끝 칸(디스크 오른쪽 테두리)이 색칠돼 있어서, 그림 끝이 곧 요소 끝이에요
 *   (머리글의 로고 ↔ 이름 간격이 그대로예요).
 *
 * 이 파일에는 화면 코드(JSX)를 넣지 않아요. 아이콘 스크립트(Node.js)도 그대로 불러 쓸 수 있게 하려는 거예요.
 * 글자 그림은 lib/pixel-path.ts가 SVG 경로로 바꾸고, components/pixel-art.tsx가 화면에 그려요.
 */

